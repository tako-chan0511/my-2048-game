import type { Board, Tile } from './types.ts'
import { assertBoard, assertTile, boardSize, integer } from './validation.ts'
export function tileValue(tile: Tile): bigint { assertTile(tile); return 1n << BigInt(tile.power) }
export function boardTotal(board: Board): bigint { assertBoard(board); return board.reduce((sum, tile) => sum + (tile ? tileValue(tile) : 0n), 0n) }
export function highestPower(board: Board): number { assertBoard(board); return Math.max(0, ...board.map(tile => tile?.power ?? 0)) }
export function copyBoard(board: Board): Board { return Object.freeze(board.map(tile => tile ? Object.freeze({ id: tile.id, power: tile.power }) : null)) }
export function allocateTile(id: number, power: number): Tile { const tile = { id, power }; assertTile(tile); return Object.freeze(tile) }
export function increment(value: number): number { if (!integer(value, 0, Number.MAX_SAFE_INTEGER - 1)) throw new RangeError('Counter limit exceeded'); return value + 1 }
// Empty-only boards are useful in tests but cannot be generated by createGame.
export function isGameOver(board: Board): boolean {
  const size = boardSize(board)
  const occupied = board.some(tile => tile !== null)
  if (!occupied) return true
  if (board.some(tile => tile === null)) return false
  for (let row = 0; row < size; row++) for (let col = 0; col < size; col++) {
    const power = board[row * size + col]!.power
    if (col < size - 1 && board[row * size + col + 1]!.power === power) return false
    if (row < size - 1 && board[(row + 1) * size + col]!.power === power) return false
  }
  return true
}
